    public static PyString CaseFold(PyString value)
    {
        var builder = CreateBuilder(value, value.Utf8Bytes.Length);
        var source = value.Utf8Bytes.Span;
        for (var byteIndex = 0; byteIndex < source.Length;)
        {
            Rune.DecodeFromUtf8(source[byteIndex..], out var rune, out var runeLength);
            if (TryGetFoldedCode(rune.Value, out var foldedCode))
            {
                builder.AppendString(new Rune(foldedCode).ToString());
            }
            else if (GetFullFold(rune.Value) is { } folded)
            {
                builder.AppendString(folded);
            }
            else
            {
                builder.Append(source.Slice(byteIndex, runeLength));
            }

            byteIndex += runeLength;
        }

        return builder.ToPyStringAndRelease();
    }

    private static bool TryGetFoldedCode(int code, out int folded)
    {
        var lo = 0;
        var hi = FoldDeltaRanges.Length - 1;
        while (lo <= hi)
        {
            var mid = lo + ((hi - lo) >> 1);
            var (rangeLo, rangeHi, delta) = FoldDeltaRanges[mid];
            if (code < rangeLo)
            {
                hi = mid - 1;
            }
            else if (code > rangeHi)
            {
                lo = mid + 1;
            }
            else
            {
                folded = code + delta;
                return true;
            }
        }

        lo = 0;
        hi = FoldSinglePairs.Length - 1;
        while (lo <= hi)
        {
            var mid = lo + ((hi - lo) >> 1);
            var (singleCode, singleFolded) = FoldSinglePairs[mid];
            if (code < singleCode)
            {
                hi = mid - 1;
            }
            else if (code > singleCode)
            {
                lo = mid + 1;
            }
            else
            {
                folded = singleFolded;
                return true;
            }
        }

        folded = 0;
        return false;
    }

    private static string? GetFullFold(int code)
    {
        var lo = 0;
        var hi = FoldFullEntries.Length - 1;
        while (lo <= hi)
        {
            var mid = lo + ((hi - lo) >> 1);
            var (entryCode, entryFolded) = FoldFullEntries[mid];
            if (code < entryCode)
            {
                hi = mid - 1;
            }
            else if (code > entryCode)
            {
                lo = mid + 1;
            }
            else
            {
                return entryFolded;
            }
        }

        return null;
    }
