"""Regenerate finite full-case expansion data and CPython goldens from the repo root.

Run with CPython 3.13 (Unicode 15.1): python -X utf8 -I tools/UnicodeCaseExpansions/generate.py
Single-scalar mappings remain with Lython's existing managed Rune/title rules.
"""

import json
from pathlib import Path
import sys
import unicodedata


def generated_files():
    if sys.version_info[:2] != (3, 13) or unicodedata.unidata_version != "15.1.0":
        raise RuntimeError("Use CPython 3.13 with Unicode 15.1.0 for these pinned mappings.")
    rows = []
    for cp in range(0x110000):
        if 0xD800 <= cp <= 0xDFFF:
            continue
        ch = chr(cp)
        upper, title = ch.upper(), ch.title()
        if len(upper) > 1 or len(title) > 1:
            rows.append((ch, upper, title, ch.capitalize(), ch.swapcase()))
    assert len(rows) == 102 and sum(len(row[2]) > 1 for row in rows) == 48
    literal = lambda value: json.dumps(value, ensure_ascii=True)
    entries = []
    for ch, upper, title, _, _ in rows:
        if len(upper) > 1 and upper == title:
            entries.append(f"            (0x{ord(ch):04X}, CaseMapping.Upper or CaseMapping.Title) => {literal(upper)},")
        else:
            for mapping, value in [("Upper", upper), ("Title", title)]:
                if len(value) > 1:
                    entries.append(f"            (0x{ord(ch):04X}, CaseMapping.{mapping}) => {literal(value)},")
    data = """using System.Text;

namespace Lokad.Lython.Runtime.Text;

internal static partial class PyStringOps
{
    // Generated by tools/UnicodeCaseExpansions/generate.py from CPython 3.13,
    // Unicode 15.1. Complete multi-scalar uppercase/title expansions only;
    // single-scalar casing and contextual rules remain in the existing kernel.
    private static string? GetCaseExpansion(Rune rune, CaseMapping mapping)
        => (rune.Value, mapping) switch
        {
ENTRIES
            _ => null,
        };
}
""".replace("ENTRIES", "\n".join(entries))
    native = """using Lokad.Lython.Runtime.Text;

namespace Lokad.Lython.Tests;

public sealed class FullCaseExpansionTests
{
    // Generated independent CPython 3.13 / Unicode 15.1 outputs, covering
    // every scalar with a multi-scalar uppercase or titlecase expansion.
    [Theory]
ROWS
    public void FullMappingsFollowPython(string source, string upper, string title, string capitalized, string swapped)
    {
        var value = PyString.FromString(source);
        Assert.Equal(upper, PyStringOps.Upper(value).AsString());
        Assert.Equal(title, PyStringOps.Title(value).AsString());
        Assert.Equal(capitalized, PyStringOps.Capitalize(value).AsString());
        Assert.Equal(swapped, PyStringOps.SwapCase(value).AsString());
    }
}
""".replace("ROWS", "\n".join("    [InlineData(" + ", ".join(map(literal, row)) + ")]" for row in rows))
    source = "for text in " + repr("".join(row[0] for row in rows)) + ":\n print(text.upper().encode('utf-8').hex(),text.title().encode('utf-8').hex(),text.capitalize().encode('utf-8').hex(),text.swapcase().encode('utf-8').hex())"
    expected = "".join(" ".join(value.encode("utf-8").hex() for value in row[1:]) + "\n" for row in rows)
    public = """using Lokad.Lython.Tests.Harness;

namespace Lokad.Lython.PublicApi.Tests;

public sealed class FullCaseExpansionExecutionTests
{
    // Generated independent CPython 3.13 / Unicode 15.1 stdout golden.
    [Fact]
    public async Task AllFullExpansionsMatchPythonUnderBothExecutionApis()
    {
        const string source = SOURCE;
        const string expected = EXPECTED;
        var budget = new LythonMemoryBudget(2 * 1024 * 1024);
        using var script = new LythonEngine().Compile(source, budget);
        Assert.True(script.IsValid);
        var baseline = budget.ReservedBytes;
        foreach (var asynchronous in new[] { false, true })
        {
            using var result = asynchronous ? await script.RunAsync(new MockLythonHost()) : script.Run(new MockLythonHost());
            Assert.True(result.Success, result.Failure?.Message);
            Assert.Equal(expected, result.StandardOutput);
            result.Dispose();
            Assert.Equal(baseline, budget.ReservedBytes);
        }
        script.Dispose();
        Assert.Equal(0, budget.ReservedBytes);
    }
}
""".replace("SOURCE", literal(source)).replace("EXPECTED", literal(expected))
    return {
        "src/Lokad.Lython/Runtime/Text/PyStringOps.CaseExpansions.cs": data,
        "tests/Lokad.Lython.Tests/FullCaseExpansionTests.cs": native,
        "tests/Lokad.Lython.PublicApi.Tests/FullCaseExpansionExecutionTests.cs": public,
    }


if __name__ == "__main__":
    root = Path(__file__).resolve().parents[2]
    for name, content in generated_files().items():
        (root / name).write_text(content, encoding="utf-8")
        print(name)
